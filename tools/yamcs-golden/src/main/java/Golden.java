import java.io.PrintWriter;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Random;

import org.yamcs.ProcessorConfig;
import org.yamcs.YConfiguration;
import org.yamcs.mdb.ContainerProcessingResult;
import org.yamcs.mdb.Mdb;
import org.yamcs.mdb.MdbFactory;
import org.yamcs.mdb.MetaCommandProcessor;
import org.yamcs.mdb.MetaCommandProcessor.CommandBuildResult;
import org.yamcs.mdb.ProcessorData;
import org.yamcs.mdb.XtceTmExtractor;
import org.yamcs.parameter.AggregateValue;
import org.yamcs.parameter.ArrayValue;
import org.yamcs.parameter.ParameterValue;
import org.yamcs.parameter.Value;
import org.yamcs.utils.StringConverter;
import org.yamcs.utils.TimeEncoding;
import org.yamcs.xtce.MetaCommand;
import org.yamcs.xtce.SequenceContainer;

/**
 * Runs the cases from tests/golden/cases.txt through Yamcs and writes the results in the format read by
 * tests/golden.rs.
 * <p>
 * Case lines (fields separated by " | "):
 *
 * <pre>
 * tm | file.xml | /container/start | packet-hex
 * tmrand | file.xml | /container/start | prefix-hex | total-length | count
 * tc | file.xml | /command/name | arg1=value1 ; arg2=value2
 * </pre>
 *
 * Output (fields separated by tabs):
 *
 * <pre>
 * tm   file.xml   /container/start   packet-hex
 * param   /qualified/name   raw=TYPE:value   eng=TYPE:value   [invalid]
 * error   message
 * tc   file.xml   /command/name   arg1=value1 ; arg2=value2
 * binary   hex
 * arg   name   raw=TYPE:value   eng=TYPE:value
 * error   message
 * </pre>
 *
 * The parameters are in the extraction order, the arguments are sorted by name.
 */
public class Golden {
    static Path xtceDir;
    static Map<String, Mdb> mdbs = new HashMap<>();

    public static void main(String[] args) throws Exception {
        if (args.length != 3) {
            System.err.println("Usage: Golden <xtce-dir> <cases.txt> <expected.txt>");
            System.exit(1);
        }
        YConfiguration.setupTest(null);
        TimeEncoding.setUp();
        xtceDir = Path.of(args[0]);

        List<String> lines = Files.readAllLines(Path.of(args[1]));
        try (PrintWriter out = new PrintWriter(Files.newBufferedWriter(Path.of(args[2])))) {
            out.println("# generated by tools/yamcs-golden from cases.txt; do not edit");
            for (String line : lines) {
                line = line.strip();
                if (line.isEmpty() || line.startsWith("#")) {
                    continue;
                }
                String[] f = line.split("\\s*\\|\\s*", -1);
                switch (f[0]) {
                case "tm" -> tm(out, f[1], f[2], f[3]);
                case "tmrand" -> {
                    byte[] prefix = StringConverter.hexStringToArray(f[3]);
                    int len = Integer.parseInt(f[4]);
                    int count = Integer.parseInt(f[5]);
                    Random rand = new Random(line.hashCode());
                    for (int i = 0; i < count; i++) {
                        byte[] p = new byte[len];
                        rand.nextBytes(p);
                        System.arraycopy(prefix, 0, p, 0, prefix.length);
                        tm(out, f[1], f[2], StringConverter.arrayToHexString(p).toLowerCase());
                    }
                }
                case "tc" -> tc(out, f[1], f[2], f.length > 3 ? f[3] : "");
                default -> throw new IllegalArgumentException("Invalid case line: " + line);
                }
            }
        }
    }

    static Mdb mdb(String file) {
        return mdbs.computeIfAbsent(file, f -> {
            Map<String, Object> m = new HashMap<>();
            m.put("type", "xtce");
            m.put("spec", yamcsCompatible(xtceDir.resolve(f)).toString());
            return MdbFactory.createInstance(List.of(YConfiguration.wrap(m)), false, false);
        });
    }

    /**
     * Yamcs creates the system parameters (/yamcs/...) on the fly only when referenced with an absolute path; the
     * simulator.xml test file uses relative references (../../yamcs/...) so a fixed copy is loaded instead.
     */
    static Path yamcsCompatible(Path file) {
        try {
            String s = Files.readString(file);
            String fixed = s.replace("\"../../yamcs/", "\"/yamcs/");
            if (fixed.equals(s)) {
                return file;
            }
            Path tmp = Files.createTempFile("golden", ".xml");
            tmp.toFile().deleteOnExit();
            Files.writeString(tmp, fixed);
            return tmp;
        } catch (java.io.IOException e) {
            throw new java.io.UncheckedIOException(e);
        }
    }

    static void tm(PrintWriter out, String file, String container, String hex) {
        out.println(String.join("\t", "tm", file, container, hex));
        Mdb mdb = mdb(file);
        SequenceContainer sc = mdb.getSequenceContainer(container);
        if (sc == null) {
            throw new IllegalArgumentException("No container " + container + " in " + file);
        }
        XtceTmExtractor extractor = new XtceTmExtractor(mdb);
        extractor.provideAll();
        ContainerProcessingResult r = extractor.processPacket(StringConverter.hexStringToArray(hex), 0, 0, 0, sc);
        for (ParameterValue pv : r.getParameterResult()) {
            List<String> l = new ArrayList<>();
            l.add("param");
            l.add(pv.getParameter().getQualifiedName());
            l.add("raw=" + format(pv.getRawValue()));
            l.add("eng=" + format(pv.getEngValue()));
            if (pv.isInvalid()) {
                l.add("invalid");
            }
            out.println(String.join("\t", l));
        }
        Object exception = processingException(r);
        if (exception != null) {
            out.println("error\t" + oneLine(exception.toString()));
        }
    }

    static void tc(PrintWriter out, String file, String cmdName, String argList) {
        out.println(String.join("\t", "tc", file, cmdName, argList));
        Mdb mdb = mdb(file);
        MetaCommand mc = mdb.getMetaCommand(cmdName);
        if (mc == null) {
            throw new IllegalArgumentException("No command " + cmdName + " in " + file);
        }
        Map<String, Object> args = new LinkedHashMap<>();
        for (String a : argList.split(";")) {
            a = a.strip();
            if (a.isEmpty()) {
                continue;
            }
            int k = a.indexOf('=');
            args.put(a.substring(0, k).strip(), a.substring(k + 1).strip());
        }
        MetaCommandProcessor mcp = new MetaCommandProcessor(new ProcessorData("golden", mdb, new ProcessorConfig()));
        try {
            CommandBuildResult r = mcp.buildCommand(mc, args, 0);
            out.println("binary\t" + StringConverter.arrayToHexString(r.getCmdPacket()).toLowerCase());
            r.getArgs().entrySet().stream()
                    .sorted(Comparator.comparing(e -> e.getKey().getName()))
                    .forEach(e -> out.println(String.join("\t", "arg", e.getKey().getName(),
                            "raw=" + format(e.getValue().getRawValue()),
                            "eng=" + format(e.getValue().getEngValue()))));
        } catch (Exception e) {
            out.println("error\t" + oneLine(e.toString()));
        }
    }

    // the field is not public
    static Object processingException(ContainerProcessingResult r) {
        try {
            var f = ContainerProcessingResult.class.getDeclaredField("exception");
            f.setAccessible(true);
            return f.get(r);
        } catch (ReflectiveOperationException e) {
            throw new IllegalStateException(e);
        }
    }

    static String oneLine(String s) {
        return s.replaceAll("\\s+", " ");
    }

    /**
     * TYPE:value. Floats are formatted with Float/Double.toString, strings and binaries in hex (the strings
     * UTF-8 encoded), timestamps as milliseconds since 1970 TAI, enumerated values as key:label.
     */
    static String format(Value v) {
        if (v == null) {
            return "-";
        }
        String t = v.getType().name();
        String s = switch (v.getType()) {
        case SINT32 -> Integer.toString(v.getSint32Value());
        case UINT32 -> Integer.toUnsignedString(v.getUint32Value());
        case SINT64 -> Long.toString(v.getSint64Value());
        case UINT64 -> Long.toUnsignedString(v.getUint64Value());
        case FLOAT -> Float.toString(v.getFloatValue());
        case DOUBLE -> Double.toString(v.getDoubleValue());
        case BOOLEAN -> Boolean.toString(v.getBooleanValue());
        case STRING -> hex(v.getStringValue().getBytes(StandardCharsets.UTF_8));
        case BINARY -> hex(v.getBinaryValue());
        case TIMESTAMP -> Long.toString(v.getTimestampValue());
        case ENUMERATED -> v.getSint64Value() + ":" + v.getStringValue();
        case AGGREGATE -> {
            AggregateValue av = (AggregateValue) v;
            List<String> l = new ArrayList<>();
            for (int i = 0; i < av.numMembers(); i++) {
                l.add(av.getMemberName(i) + "=" + format(av.getMemberValue(i)));
            }
            yield "{" + String.join(",", l) + "}";
        }
        case ARRAY -> {
            ArrayValue av = (ArrayValue) v;
            List<String> dims = new ArrayList<>();
            for (int d : av.getDimensions()) {
                dims.add(Integer.toString(d));
            }
            List<String> l = new ArrayList<>();
            for (int i = 0; i < av.flatLength(); i++) {
                l.add(format(av.getElementValue(i)));
            }
            t = "ARRAY[" + String.join(",", dims) + "]";
            yield "[" + String.join(",", l) + "]";
        }
        default -> throw new IllegalArgumentException("Unexpected value type " + v.getType());
        };
        return t + ":" + s;
    }

    static String hex(byte[] b) {
        return StringConverter.arrayToHexString(b).toLowerCase();
    }
}
